function findTopicId(sectionId: ReferenceSectionId, title: string): string {
  const section = ALL_REFERENCE_SECTIONS.find((item) => item.id === sectionId)!;
  const hintedTitle = TOPIC_HINTS[sectionId]?.find(([pattern]) => pattern.test(title))?.[1];
  const fallbackTitle = DEFAULT_TOPIC[sectionId];
  return section.topics.find((item) => item.title === hintedTitle)?.id
    ?? section.topics.find((item) => item.title === fallbackTitle)?.id
    ?? section.topics[0].id;
}

function cleanText(text: string): string {
  return normalizeCitationTypography(stripCitationServicePrefix(text))
    .replace(/\s*\([^)]*(?:лекц|предмет|джерел|повний шар)[^)]*\)\s*/giu, ' ')
    .replace(/\s*З архівної лекції(?:\s*\([^)]*\))?\s*;?\s*/giu, ' ')
    .replace(/\s*Наповнення етапів[^.]*\.\s*/giu, ' ')
    .replace(/\s*Наповнення з архівного[^.]*\.?/giu, ' ')
    .replace(/\s*Не дублює картку[^.]*\.\s*/giu, ' ')
    .replace(/\s*—?\s*under_review\b[^.]*\.?/giu, ' ')
    .replace(/\s*не verified НПА\.?/giu, ' ')
    .replace(/\s*Архівний конспект[^.]*\.?/giu, ' ')
    .replace(/\s*Текст з архівного[^.]*\.?/giu, ' ')
    .replace(/\s*Матеріал з архівної лекції[^.]*\.?/giu, ' ')
    .replace(/\s*\(ущільнення[^)]*\)\s*/giu, ' ')
    .replace(/^«([^»]+)»\s*пояснює операційні акценти розділу[^.]+\.\s*/iu, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s*\.\s*\./g, '.')
    .trim();
}

function toAnswerBlocks(situation: WorkingSituation): SituationAnswerBlock[] {
  const result: SituationAnswerBlock[] = [];
  const seen = new Set<string>();

  for (const phase of situation.phases) {
    if (!phase.isApplicable) continue;
    for (const subsection of phase.subsections) {
      const citationText = subsection.citations.map((citation) => cleanText(citation.text)).filter(Boolean).join('\n\n');
      const content = citationText || cleanText(subsection.content);
      if (!content || /щільні цитати.+наступний/iu.test(content)) continue;
      const key = `${subsection.title.toLowerCase()}::${content.slice(0, 160).toLowerCase()}`;
      if (seen.has(key)) continue;
      seen.add(key);
      result.push({
        id: subsection.id,
        title: subsection.title,
        content,
        responsibleRole: subsection.responsibleRole,
        deadlineText: subsection.deadlineText,
      });
    }
  }

  if (result.length === 0) {
    result.push({ id: `${situation.id}-summary`, title: 'Коротка відповідь', content: cleanText(situation.summary) });
  }
  return result;
}

/** Нормалізує одну архівну ситуацію в нову модель каталогу. */
export function normalizeReferenceSituation(situation: WorkingSituation): ReferenceSituation {
  const sectionId = LEGACY_SECTION_MAP[situation.categoryGroup];
  return {
    id: situation.id,
    slug: situation.slug,
    title: situation.title,
    sectionId,
    topicId: findTopicId(sectionId, situation.title),
    summary: cleanText(situation.summary) || situation.title,
    answers: toAnswerBlocks(situation),
    keyAttentionPoints: situation.keyAttentionPoints.filter(
      (point) => !/архівн|не\s+нпа|потребують перевірки|не verified|under_review|пілот/iu.test(point),
    ),
    status: situation.status,
    lastCheckDate: situation.lastCheckDate,
    relatedTermIds: situation.relatedTermIds,
    relatedFormIds: situation.relatedFormIds,
    relatedLearningTopicIds: situation.relatedLearningTopicIds,
    relatedSituationIds: situation.relatedSituationIds,
  };
}

/** Канонічний каталог ситуацій, що зберігає весь наявний контент під час міграції. */
export function normalizeReferenceSituations(situations: WorkingSituation[]): ReferenceSituation[] {
  return situations.map(normalizeReferenceSituation);
}
