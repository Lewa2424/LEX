import { ActionPhase, Citation, WorkingSituation } from '../../shared/types';
import { MOCK_SOURCES } from './sourcesData';

const LEC_DOC =
  MOCK_SOURCES.find((s) => s.id === 'src-lec-dokumentatsiia-tema-6') ?? MOCK_SOURCES[0];

const MARK =
  '[Цитата з архівної лекції «Ведення документації…» тема 6 — не НПА; потрібна перевірка за офіційним джерелом]';

function cit(id: string, text: string, page: string, note?: string): Citation {
  return {
    id,
    text: `${MARK} ${text}`,
    source: LEC_DOC,
    sectionOrPage: page,
    status: 'under_review',
    editorialNote: note,
  };
}

const PHASE_META: Array<{ id: ActionPhase['id']; order: number; title: string; description: string }> = [
  { id: 'preparation', order: 1, title: 'Підготовка', description: 'Що підготувати до процедури.' },
  { id: 'identification', order: 2, title: 'Виявлення та оцінка', description: 'Кого стосується і які умови.' },
  { id: 'prevention', order: 3, title: 'Проведення', description: 'Як виконати основну дію.' },
  { id: 'response', order: 4, title: 'Реагування на відхилення', description: 'Що робити при незадовільному результаті.' },
  { id: 'investigation', order: 5, title: 'Оформлення', description: 'Як зафіксувати результат.' },
  { id: 'recovery', order: 6, title: 'Допуск і покращення', description: 'Умови допуску та типові уточнення.' },
];

type SubIn = {
  phase: ActionPhase['id'];
  title: string;
  content: string;
  citations?: Citation[];
  isRequired?: boolean;
  responsibleRole?: string;
  deadlineText?: string;
};

function phases(prefix: string, subs: SubIn[], applicable: Partial<Record<ActionPhase['id'], boolean>> = {}): ActionPhase[] {
  return PHASE_META.map((meta) => {
    const list = subs
      .filter((s) => s.phase === meta.id)
      .map((s, i) => ({
        id: `${prefix}-${meta.id}-${i + 1}`,
        title: s.title,
        content: s.content,
        citations: s.citations ?? [],
        isRequired: s.isRequired ?? true,
        responsibleRole: s.responsibleRole,
        deadlineText: s.deadlineText,
      }));
    // За замовчуванням етап видимий лише якщо є підрозділи.
    // Явний applicable[id] дозволяє показати порожній слот (draft) або примусово сховати.
    const explicit = applicable[meta.id];
    const isApplicable = explicit !== undefined ? explicit : list.length > 0;
    return {
      ...meta,
      isApplicable,
      subsections: list.length
        ? list
        : isApplicable
          ? [
              {
                id: `${prefix}-${meta.id}-todo`,
                title: 'Наповнення',
                content: 'Щільні цитати з корпусу — наступний densify-прохід.',
                citations: [],
                isRequired: false,
              },
            ]
          : [],
    };
  });
}

function sit(params: {
  id: string;
  slug: string;
  title: string;
  summary: string;
  points: string[];
  prefix: string;
  status?: WorkingSituation['status'];
  relatedFormIds?: string[];
  relatedSituationIds?: string[];
  subs: SubIn[];
  applicable?: Partial<Record<ActionPhase['id'], boolean>>;
}): WorkingSituation {
  return {
    id: params.id,
    slug: params.slug,
    title: params.title,
    categoryGroup: 'preparation_admission',
    summary: params.summary,
    keyAttentionPoints: params.points,
    status: params.status ?? 'under_review',
    lastCheckDate: '05.09.2026',
    relatedTermIds: [],
    relatedFormIds: params.relatedFormIds ?? [],
    relatedLearningTopicIds: [],
    relatedSituationIds: params.relatedSituationIds ?? [],
    phases: phases(params.prefix, params.subs, params.applicable),
  };
}

